        /// <summary>
        /// 获取安全的文件名（移除非法字符）
        /// </summary>
        private string GetSafeFileName(string fileName)
        {
            if (string.IsNullOrWhiteSpace(fileName))
            {
                return "未命名";
            }

            // 替换文件名中的非法字符
            char[] invalidChars = Path.GetInvalidFileNameChars();
            foreach (char c in invalidChars)
            {
                fileName = fileName.Replace(c, '_');
            }

            // 替换其他可能导致问题的字符
            fileName = fileName.Replace("\\", "_")
                              .Replace("/", "_")
                              .Replace(":", "_")
                              .Replace("*", "_")
                              .Replace("?", "_")
                              .Replace("\"", "_")
                              .Replace("<", "_")
                              .Replace(">", "_")
                              .Replace("|", "_");

            // 移除多余的下划线
            while (fileName.Contains("__"))
            {
                fileName = fileName.Replace("__", "_");
            }

            // 移除文件名开头和末尾的下划线
            fileName = fileName.Trim('_');

            // 如果文件名为空，使用默认值
            if (string.IsNullOrWhiteSpace(fileName))
            {
                fileName = "未命名";
            }

            // 限制文件名长度
            if (fileName.Length > 100)
            {
                fileName = fileName.Substring(0, 100);
            }

            return fileName;
        }

        /// <summary>
        /// 立即处理要素（在获取时直接处理）
        /// </summary>
        private void ProcessFeatureImmediately(Feature feature, Polygon geometry, StringBuilder content, int featureIndex)
        {
            try
            {
                LogInfo($"立即处理要素 {featureIndex}，几何类型: {geometry.GeometryType}，环数: {geometry.PartCount}");

                // 根据配置的输出字段获取值
                var fieldValues = new List<string>();

                foreach (var outputField in OutputFields.Where(f => f.IsEnabled))
                {
                    string value = "";

                    switch (outputField.FieldName)
                    {
                        case "点数":
                            value = ""; // 稍后计算
                            break;
                        case ",":
                            value = ",";
                            break;
                        case "地块面积":
                            value = GetPlotAreaValue(feature, geometry);
                            LogInfo($"地块面积: {value}");
                            break;
                        case "地块编号":
                            value = GetPlotNumberValue(feature, featureIndex);
                            LogInfo($"地块编号: {value}");
                            break;
                        case "地块名称":
                            value = GetPlotNameValue(feature, featureIndex);
                            LogInfo($"地块名称: {value}");
                            break;
                        case "图形类型":
                            value = "面"; // 固定为面
                            break;
                        case "公顷4位":
                            // 动态计算面积(公顷)，保留4位小数
                            // Area单位通常是平方米，转换为公顷需要除以10000
                            value = (geometry.Area / 10000.0).ToString("F4");
                            break;
                        case "公顷6位":
                            // 动态计算面积(公顷)，保留6位小数
                            value = (geometry.Area / 10000.0).ToString("F6");
                            break;
                        case "图幅号":
                            value = GetFieldValueByMapping("图幅号", feature) ?? "";
                            LogInfo($"图幅号: {value}");
                            break;
                        case "地块用途":
                            value = GetFieldValueByMapping("地块用途", feature) ?? "";
                            LogInfo($"地块用途: {value}");
                            break;
                        case "地类编码":
                            value = GetFieldValueByMapping("地类编码", feature) ?? "";
                            LogInfo($"地类编码: {value}");
                            break;
                        case "@":
                            value = "@";
                            break;
                        default:
                            value = GetFieldValueByMapping(outputField.FieldName, feature) ?? "";
                            break;
                    }

                    fieldValues.Add(value);
                }

                // 计算总点数和写入坐标
                WriteFeatureCoordinatesImmediately(geometry, content, fieldValues, featureIndex);

                LogInfo($"要素 {featureIndex} 处理完成");
            }
            catch (Exception ex)
            {
                LogError($"立即处理要素 {featureIndex} 时出错: {ex.Message}");
                LogError($"异常详情: {ex}");
            }
        }

