        /// <summary>
        /// 执行转换（异步版本，避免UI阻塞）
        /// </summary>
        private async Task ExecuteAsync()
        {
            if (SelectedPolygonLayer == null)
            {
                StatusMessage = "请选择面图层。";
                return;
            }

            if (string.IsNullOrEmpty(OutputPath))
            {
                StatusMessage = "请选择输出文件夹。";
                return;
            }

            // 检查输出路径是否为有效文件夹
            if (!Directory.Exists(OutputPath))
            {
                StatusMessage = "输出路径不是有效的文件夹。";
                return;
            }

            // 在UI线程中更新状态（不等待，避免阻塞）
            _ = System.Windows.Application.Current.Dispatcher.BeginInvoke(() =>
            {
                IsProcessing = true;
                CancelRequested = false;
                Progress = 0;
                IsProgressIndeterminate = true;
                StatusMessage = "正在转换要素...";
                LogContent = "";
            });
            
            // 等待一小段时间确保UI更新
            await Task.Delay(50);

            try
            {

                    LogInfo($"开始转换 - 图层: {SelectedPolygonLayer.Name}", true);
                    LogInfo($"输出文件夹: {OutputPath}", true);

                    await QueuedTask.Run(() =>
                {
                    try
                    {
                        if (CancelRequested) return;

                        var featureClass = SelectedPolygonLayer.GetFeatureClass();
                        if (featureClass == null)
                        {
                            LogError("无法获取要素类");
                            return;
                        }

                        // 是否仅处理选择集：开关开启且确有选择
                        bool useSel = UseSelection && SelectedPolygonLayer.SelectionCount > 0;
                        var cursor = SelectionUtils.GetSelectionOrAllCursor(SelectedPolygonLayer, useSel, null, false);
                        if (cursor == null)
                        {
                            LogError("无法获取要素游标");
                            return;
                        }
                        int featureCount = 0;
                        int processedCount = 0;
                        _processedFeatureCount = 0;

                        // 首先计算总要素数
                        var totalFeatures = new List<Feature>();
                        while (cursor.MoveNext())
                        {
                            var feature = cursor.Current as Feature;
                            if (feature != null)
                            {
                                totalFeatures.Add(feature);
                            }
                        }
                        cursor.Dispose();

                        LogInfo($"找到 {totalFeatures.Count} 个要素，开始处理", true);

                        if (GroupByField && !string.IsNullOrEmpty(GroupByFieldName))
                        {
                            // 按字段分组导出：每个字段值生成单独文件
                            LogInfo($"按字段分组导出模式：按 {GroupByFieldName} 字段值分组");
                            ProcessFeaturesByGroupFieldSync(totalFeatures);
                            processedCount = totalFeatures.Count;
                        }
                        else if (ExportSeparately)
                        {
                            // 分块导出：每个要素生成单独文件
                            LogInfo("分块导出模式：每个要素生成单独文件");

                            // 处理所有要素
                            for (int i = 0; i < totalFeatures.Count; i++)
                            {
                                if (CancelRequested) return;

                                var feature = totalFeatures[i];
                                featureCount = i + 1;

                                try
                                {
                                    // 极简日志输出
                                    if (featureCount == 1 || featureCount % 200 == 0)
                                    {
                                        LogInfo($"处理要素 {featureCount}");
                                    }

                                    // 在QueuedTask中获取几何对象并处理
                                    var shape = feature.GetShape();

                                    if (shape is Polygon geometry)
                                    {
                                        // 为每个要素生成单独的文件（已经在QueuedTask中）
                                        ProcessSingleFeatureToFileInTaskSync(feature, geometry, featureCount);
                                        processedCount++;
                                    }
                                    else
                                    {
                                        // 移除警告日志，避免大量输出
                                    }
                                }
                                catch (Exception shapeEx)
                                {
                                    LogError($"处理要素 {featureCount} 时出错: {shapeEx.Message}");
                                }

                                // 减少UI更新频率，提升性能（每100个更新一次）
                                if (featureCount % 100 == 0 || featureCount == totalFeatures.Count)
                                {
                                    var progress = (int)((double)featureCount / totalFeatures.Count * 100);
                                    var currentCount = featureCount;
                                    var totalCount = totalFeatures.Count;

                                    _ = System.Windows.Application.Current?.Dispatcher.BeginInvoke(() =>
                                    {
                                        Progress = progress;
                                        StatusMessage = $"已处理 {currentCount}/{totalCount} 个要素";
                                    }, System.Windows.Threading.DispatcherPriority.Background);
                                }
                            }
                        }
                        else
                        {
                            // 合并导出：所有要素生成一个文件
                            LogInfo("合并导出模式：所有要素生成一个文件");
                            ProcessAllFeaturesToSingleFileSync(totalFeatures);
                            processedCount = totalFeatures.Count;
                        }

                        if (processedCount == 0)
                        {
                            LogWarning("没有成功处理任何要素");
                            return;
                        }

                        LogInfo($"转换完成，成功处理了 {processedCount} 个要素");
                    }
                    catch (Exception ex)
                    {
                        LogError($"转换过程中出错: {ex.Message}");
                    }
                });
            }
            catch (Exception ex)
            {
                _ = System.Windows.Application.Current.Dispatcher.BeginInvoke(() =>
                {
                    StatusMessage = $"转换失败: {ex.Message}";
                });
                LogError($"转换失败: {ex.Message}");
            }
            finally
            {
                // 确保UI状态更新在UI线程中进行（不等待）
                _ = System.Windows.Application.Current.Dispatcher.BeginInvoke(() =>
                {
                    IsProcessing = false;
                    IsProgressIndeterminate = false;
                    Progress = 100;
                    if (!CancelRequested)
                    {
                        StatusMessage = "转换完成。";
                    }
                    else
                    {
                        StatusMessage = "操作已取消。";
                    }
                });
            }
        }

