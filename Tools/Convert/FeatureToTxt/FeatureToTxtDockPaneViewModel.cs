        private void AddOutputField(string fieldName)
        {
            if (string.IsNullOrEmpty(fieldName)) return;
            if (fieldName.StartsWith("---") && fieldName.EndsWith("---")) return; // 忽略分隔标题

            // 检查是否已存在
            if (OutputFields.Any(f => f.FieldName == fieldName))
            {
                StatusMessage = $"字段 '{fieldName}' 已存在";
                return;
            }

            // 在@符号前插入新字段
            var atIndex = OutputFields.ToList().FindIndex(f => f.FieldName == "@");
            if (atIndex >= 0)
            {
                // 插入新字段
                var isAutoGenerated = fieldName == "点数" || fieldName == "图形类型" || fieldName == "公顷4位" || fieldName == "公顷6位";
                OutputFields.Insert(atIndex, new OutputFieldItem(fieldName, GetFieldDescription(fieldName), true, isAutoGenerated));
                // 插入逗号分隔符
                OutputFields.Insert(atIndex + 1, new OutputFieldItem(",", "分隔符", false, true));
            }

            NotifyPropertyChanged(() => OutputFieldsCount);
            StatusMessage = $"已添加字段 '{fieldName}'";
            LogInfo($"添加输出字段: {fieldName}");
        }

        /// <summary>
        /// 添加全部实际字段（根据 FieldInfos）
        /// </summary>
        private void AddAllActualFields()
        {
            if (FieldInfos == null || FieldInfos.Count == 0)
            {
                StatusMessage = "没有可用的实际字段";
                return;
            }
            var added = 0;
            foreach (var fi in FieldInfos)
            {
                var name = fi.FieldName;
                if (!OutputFields.Any(f => f.FieldName == name))
                {
                    AddOutputField(name);
                    added++;
                }
            }
            StatusMessage = added > 0 ? $"已添加 {added} 个实际字段" : "没有新增字段（均已存在）";
        }

        /// <summary>
        /// 添加映射到的推荐字段（依据 _fieldMappings 自动匹配）
        /// </summary>
        private void AddMappedFields()
        {
            if (FieldInfos == null || FieldInfos.Count == 0)
            {
                StatusMessage = "没有可用的实际字段用于匹配";
                return;
            }
            var fieldNames = FieldInfos.Select(f => f.FieldName).ToList();
            var added = 0;
            foreach (var mapping in _fieldMappings)
            {
                var matched = FindMatchingField(fieldNames, mapping.Value);
                if (!string.IsNullOrEmpty(matched) && !OutputFields.Any(f => f.FieldName == matched))
                {
                    AddOutputField(matched);
                    added++;
                }
            }
            StatusMessage = added > 0 ? $"已添加 {added} 个推荐字段" : "未找到可添加的推荐字段";
        }

