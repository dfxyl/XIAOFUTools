        /// <summary>
        /// 构造函数
        /// </summary>
        public FeatureToTxtDockPaneViewModel()
        {
            try
            {
                // 初始化基本属性（必须成功）
                PolygonLayers = new ObservableCollection<FeatureLayer>();
                FieldInfos = new ObservableCollection<FieldDisplayInfo>();
                TextFormats = new ObservableCollection<string> { "UTF-8", "UTF-8(无BOM)", "ANSI", "GBK", "Unicode" };
                OutputFields = new ObservableCollection<OutputFieldItem>();
                AvailableFields = new ObservableCollection<string>();
                GroupableFields = new ObservableCollection<string>();
                
                StatusMessage = "正在初始化...";
                LogContent = "";
                Progress = 0;
                IsProgressIndeterminate = false;

                // 注册编码提供程序以支持GB2312、GBK等编码
                try
                {
                    Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
                    LogInfo("编码提供程序注册成功");

                    // 验证关键编码是否可用
                    ValidateEncodingSupport();
                }
                catch (Exception ex)
                {
                    LogError($"编码提供程序注册失败: {ex.Message}");
                }

                // 加载头部信息配置
                try
                {
                    LoadHeaderConfigs();
                }
                catch (Exception ex)
                {
                    LogError($"加载头部配置失败: {ex.Message}");
                    // 确保至少有默认配置
                    if (HeaderConfigs == null || HeaderConfigs.Count == 0)
                    {
                        HeaderConfigs = new ObservableCollection<HeaderConfig>();
                    }
                }

                // 设置默认输出路径为工程位置
                try
                {
                    SetDefaultOutputPath();
                }
                catch (Exception ex)
                {
                    LogError($"设置默认输出路径失败: {ex.Message}");
                    OutputPath = "";
                }

                // 初始化默认输出字段
                try
                {
                    InitializeDefaultOutputFields();
                }
                catch (Exception ex)
                {
                    LogError($"初始化默认输出字段失败: {ex.Message}");
                }

                LogInfo("ViewModel已初始化");
                StatusMessage = "就绪";

                // 订阅地图选择变化事件
                try
                {
                    _mapSelectionChangedToken = MapSelectionChangedEvent.Subscribe(OnMapSelectionChanged);
                }
                catch (Exception ex)
                {
                    LogError($"订阅地图选择变化事件失败: {ex.Message}");
                }

                // 初始化一次选择信息
                try
                {
                    UpdateSelectionInfo();
                }
                catch (Exception ex)
                {
                    LogError($"更新选择信息失败: {ex.Message}");
                }
            }
            catch (Exception ex)
            {
                // 如果构造函数完全失败，至少记录错误
                System.Diagnostics.Debug.WriteLine($"FeatureToTxtDockPaneViewModel构造函数失败: {ex.Message}");
                System.Diagnostics.Debug.WriteLine($"堆栈: {ex.StackTrace}");
                
                // 确保基本集合被初始化，避免NullReferenceException
                PolygonLayers = PolygonLayers ?? new ObservableCollection<FeatureLayer>();
                FieldInfos = FieldInfos ?? new ObservableCollection<FieldDisplayInfo>();
                TextFormats = TextFormats ?? new ObservableCollection<string> { "UTF-8", "ANSI" };
                OutputFields = OutputFields ?? new ObservableCollection<OutputFieldItem>();
                AvailableFields = AvailableFields ?? new ObservableCollection<string>();
                GroupableFields = GroupableFields ?? new ObservableCollection<string>();
                HeaderConfigs = HeaderConfigs ?? new ObservableCollection<HeaderConfig>();
                
                StatusMessage = $"初始化失败: {ex.Message}";
                LogContent = $"错误: {ex.Message}\n{ex.StackTrace}";
                
                throw; // 重新抛出异常，让上层捕获
            }
        }

        /// <summary>
        /// 设置默认输出路径为工程位置
        /// </summary>
        private void SetDefaultOutputPath()
        {
            try
            {
                // 尝试获取当前工程路径
                var project = Project.Current;
                if (project != null && !string.IsNullOrEmpty(project.Path))
                {
                    var projectDir = Path.GetDirectoryName(project.Path);
                    if (!string.IsNullOrEmpty(projectDir) && Directory.Exists(projectDir))
                    {
                        OutputPath = projectDir;
                        LogInfo($"设置默认输出路径为工程位置: {OutputPath}");
                        return;
                    }
                }

                // 如果无法获取工程路径，使用文档文件夹
                var documentsPath = Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments);
                if (!string.IsNullOrEmpty(documentsPath) && Directory.Exists(documentsPath))
                {
                    OutputPath = documentsPath;
                    LogInfo($"设置默认输出路径为文档文件夹: {OutputPath}");
                    return;
                }

                // 最后使用桌面
                var desktopPath = Environment.GetFolderPath(Environment.SpecialFolder.Desktop);
                if (!string.IsNullOrEmpty(desktopPath) && Directory.Exists(desktopPath))
                {
                    OutputPath = desktopPath;
                    LogInfo($"设置默认输出路径为桌面: {OutputPath}");
                }
            }
            catch (Exception ex)
            {
                LogError($"设置默认输出路径时出错: {ex.Message}");
                // 如果出错，保持空路径
                OutputPath = "";
            }
        }

