        /// <summary>
        /// 按字段值分组导出要素
        /// </summary>
        private async Task ProcessFeaturesByGroupField(List<Feature> features)
        {
            try
            {
                // 检查字段是否存在
                if (string.IsNullOrEmpty(GroupByFieldName))
                {
                    LogError("分组字段名为空");
                    return;
                }

                // 按字段值分组
                var groups = new Dictionary<string, List<Feature>>();

                await QueuedTask.Run(() =>
                {
                    // 检查第一个要素确认字段存在
                    if (features.Count > 0)
                    {
                        var firstFeature = features[0];
                        var fieldIndex = firstFeature.FindField(GroupByFieldName);
                        if (fieldIndex == -1)
                        {
                            LogError($"字段 '{GroupByFieldName}' 不存在于要素类中");
                            return;
                        }
                        LogInfo($"找到分组字段: {GroupByFieldName}");
                    }

                    foreach (var feature in features)
                    {
                        try
                        {
                            // 安全获取分组字段的值
                            var fieldIndex = feature.FindField(GroupByFieldName);
                            if (fieldIndex == -1)
                            {
                                LogWarning($"要素中未找到字段 {GroupByFieldName}，归入'未知值'组");
                                if (!groups.ContainsKey("未知值"))
                                {
                                    groups["未知值"] = new List<Feature>();
                                }
                                groups["未知值"].Add(feature);
                                continue;
                            }

                            var fieldValue = feature[GroupByFieldName];
                            var groupKey = fieldValue?.ToString() ?? "未知值";

                            if (!groups.ContainsKey(groupKey))
                            {
                                groups[groupKey] = new List<Feature>();
                            }
                            groups[groupKey].Add(feature);
                        }
                        catch (Exception ex)
                        {
                            LogError($"读取字段 {GroupByFieldName} 值时出错: {ex.Message}");
                            // 将出错的要素归入"错误"组
                            if (!groups.ContainsKey("错误"))
                            {
                                groups["错误"] = new List<Feature>();
                            }
                            groups["错误"].Add(feature);
                        }
                    }
                });

                LogInfo($"按字段 {GroupByFieldName} 分组，共 {groups.Count} 个分组");

                // 处理每个分组
                int groupIndex = 0;
                foreach (var group in groups)
                {
                    if (CancelRequested) return;

                    groupIndex++;
                    var groupKey = group.Key;
                    var groupFeatures = group.Value;

                    LogInfo($"处理分组 {groupIndex}/{groups.Count}: {groupKey} ({groupFeatures.Count} 个要素)");

                    // 生成文件名（使用分组字段值）
                    var safeFileName = GetSafeFileName(groupKey);
                    var filePath = Path.Combine(OutputPath, $"{safeFileName}.txt");

                    // 创建文件内容
                    var content = new StringBuilder();

                    // 添加头部信息（使用配置）
                    content.AppendLine(GenerateFileHeader());

                    // 在QueuedTask中处理所有要素的几何操作
                    await QueuedTask.Run(() =>
                    {
                        for (int i = 0; i < groupFeatures.Count; i++)
                        {
                            if (CancelRequested) return;

                            var feature = groupFeatures[i];
                            try
                            {
                                var shape = feature.GetShape();
                                ProcessFeatureSync(feature, content, i + 1);
                            }
                            catch (Exception ex)
                            {
                                LogError($"处理要素 {i + 1} 时出错: {ex.Message}");
                            }

                            // 更新进度
                            if ((i + 1) % 10 == 0 || (i + 1) == groupFeatures.Count)
                            {
                                var totalProcessed = groups.Take(groupIndex - 1).Sum(g => g.Value.Count) + (i + 1);
                                var progress = (int)((double)totalProcessed / features.Count * 100);
                                System.Windows.Application.Current?.Dispatcher.BeginInvoke(() =>
                                {
                                    Progress = progress;
                                    StatusMessage = $"处理分组 {groupIndex}/{groups.Count}: {groupKey} ({i + 1}/{groupFeatures.Count})";
                                });
                            }
                        }
                    });

                    // 保存文件
                    var contentString = content.ToString();
                    await SaveToFile(contentString, filePath);

                    LogInfo($"分组 {groupKey} 导出完成: {safeFileName}.txt");
                }

                LogInfo($"按字段分组导出完成，共生成 {groups.Count} 个文件");
            }
            catch (Exception ex)
            {
                LogError($"按字段分组导出时出错: {ex.Message}");
            }
        }

